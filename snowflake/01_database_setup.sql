-- Database, schema, warehouse, and raw table setup for the retail orders pipeline.
-- Run once per environment (dev/prod) before 02_bronze_ingestion.sql.

CREATE DATABASE IF NOT EXISTS RETAIL_DWH;

CREATE SCHEMA IF NOT EXISTS RETAIL_DWH.BRONZE;
CREATE SCHEMA IF NOT EXISTS RETAIL_DWH.SILVER;
CREATE SCHEMA IF NOT EXISTS RETAIL_DWH.GOLD;

CREATE WAREHOUSE IF NOT EXISTS TRANSFORM_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE TABLE IF NOT EXISTS RETAIL_DWH.BRONZE.RAW_CUSTOMERS (
    CUSTOMER_ID    NUMBER,
    FIRST_NAME     VARCHAR,
    LAST_NAME      VARCHAR,
    EMAIL          VARCHAR,
    PHONE          VARCHAR,
    SIGNUP_TS      TIMESTAMP_NTZ,
    INGESTED_AT    TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RETAIL_DWH.BRONZE.RAW_ORDERS (
    ORDER_ID       NUMBER,
    CUSTOMER_ID    NUMBER,
    ORDER_TS       TIMESTAMP_NTZ,
    STATUS         VARCHAR,
    AMOUNT         NUMBER(12,2),
    SOURCE_FILE    VARCHAR,
    INGESTED_AT    TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RETAIL_DWH.BRONZE.ORDER_LOAD_QUARANTINE (
    RAW_RECORD     VARIANT,
    REASON         VARCHAR,
    SOURCE_FILE    VARCHAR,
    QUARANTINED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
