-- Privacy / governance: role separation and PII masking.
-- Basic version here; extended with full least-privilege grants in Phase 3
-- (see docs/data_dictionary.md for column-level sensitivity).

CREATE ROLE IF NOT EXISTS INGEST_ROLE;
CREATE ROLE IF NOT EXISTS TRANSFORM_ROLE;
CREATE ROLE IF NOT EXISTS ANALYST_ROLE;
CREATE ROLE IF NOT EXISTS PII_ACCESS_ROLE;

GRANT USAGE ON DATABASE RETAIL_DWH TO ROLE INGEST_ROLE, TRANSFORM_ROLE, ANALYST_ROLE;
GRANT USAGE ON SCHEMA RETAIL_DWH.BRONZE TO ROLE INGEST_ROLE, TRANSFORM_ROLE;
GRANT USAGE ON SCHEMA RETAIL_DWH.SILVER TO ROLE TRANSFORM_ROLE, ANALYST_ROLE;
GRANT USAGE ON SCHEMA RETAIL_DWH.GOLD TO ROLE ANALYST_ROLE;

GRANT INSERT, SELECT ON TABLE RETAIL_DWH.BRONZE.RAW_ORDERS TO ROLE INGEST_ROLE;
GRANT INSERT, SELECT ON TABLE RETAIL_DWH.BRONZE.RAW_CUSTOMERS TO ROLE INGEST_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA RETAIL_DWH.BRONZE TO ROLE TRANSFORM_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA RETAIL_DWH.SILVER TO ROLE ANALYST_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA RETAIL_DWH.GOLD TO ROLE ANALYST_ROLE;

-- Email/phone masking: only PII_ACCESS_ROLE sees unmasked values.
CREATE OR REPLACE MASKING POLICY RETAIL_DWH.SILVER.EMAIL_MASK AS (VAL VARCHAR)
    RETURNS VARCHAR ->
        CASE
            WHEN CURRENT_ROLE() = 'PII_ACCESS_ROLE' THEN VAL
            ELSE '***MASKED***'
        END;

CREATE OR REPLACE MASKING POLICY RETAIL_DWH.SILVER.PHONE_MASK AS (VAL VARCHAR)
    RETURNS VARCHAR ->
        CASE
            WHEN CURRENT_ROLE() = 'PII_ACCESS_ROLE' THEN VAL
            ELSE '***MASKED***'
        END;

-- Masking policies apply to base tables, not views; CUSTOMERS Silver view
-- (03_silver_transformations.sql) inherits masking from RAW_CUSTOMERS.
ALTER TABLE RETAIL_DWH.BRONZE.RAW_CUSTOMERS
    MODIFY COLUMN EMAIL SET MASKING POLICY RETAIL_DWH.SILVER.EMAIL_MASK;
ALTER TABLE RETAIL_DWH.BRONZE.RAW_CUSTOMERS
    MODIFY COLUMN PHONE SET MASKING POLICY RETAIL_DWH.SILVER.PHONE_MASK;
