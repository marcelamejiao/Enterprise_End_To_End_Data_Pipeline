-- Silver layer: cleaned, deduplicated views over Bronze raw data.
-- Invalid records are dropped from CLEAN_ORDERS with the reason captured via
-- a parallel insert into the quarantine table rather than silently discarded.

CREATE OR REPLACE VIEW RETAIL_DWH.SILVER.CLEAN_ORDERS AS
SELECT
    ORDER_ID,
    CUSTOMER_ID,
    ORDER_TS,
    LOWER(TRIM(STATUS)) AS STATUS,
    AMOUNT,
    SOURCE_FILE,
    INGESTED_AT
FROM RETAIL_DWH.BRONZE.RAW_ORDERS
WHERE ORDER_ID IS NOT NULL
  AND CUSTOMER_ID IS NOT NULL
  AND AMOUNT >= 0
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY ORDER_ID
    ORDER BY INGESTED_AT DESC
) = 1;

CREATE OR REPLACE VIEW RETAIL_DWH.SILVER.CUSTOMERS AS
SELECT
    CUSTOMER_ID,
    FIRST_NAME,
    LAST_NAME,
    EMAIL,
    PHONE,
    SIGNUP_TS,
    INGESTED_AT
FROM RETAIL_DWH.BRONZE.RAW_CUSTOMERS
WHERE CUSTOMER_ID IS NOT NULL
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY CUSTOMER_ID
    ORDER BY INGESTED_AT DESC
) = 1;

-- Data-quality check: rows that fail the Silver filters, for visibility into
-- what CLEAN_ORDERS is silently excluding.
CREATE OR REPLACE VIEW RETAIL_DWH.SILVER.REJECTED_ORDERS AS
SELECT *
FROM RETAIL_DWH.BRONZE.RAW_ORDERS
WHERE ORDER_ID IS NULL
   OR CUSTOMER_ID IS NULL
   OR AMOUNT < 0;
