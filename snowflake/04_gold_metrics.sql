-- Gold layer: business metrics as a Dynamic Table, refreshed automatically
-- as Silver changes (declarative alternative to Streams/Tasks in 05).

CREATE OR REPLACE DYNAMIC TABLE RETAIL_DWH.GOLD.DAILY_SALES
    TARGET_LAG = '10 minutes'
    WAREHOUSE = TRANSFORM_WH
AS
SELECT
    TO_DATE(ORDER_TS) AS SALES_DATE,
    STATUS,
    COUNT(*) AS ORDER_COUNT,
    SUM(AMOUNT) AS TOTAL_REVENUE,
    AVG(AMOUNT) AS AVG_ORDER_VALUE
FROM RETAIL_DWH.SILVER.CLEAN_ORDERS
GROUP BY 1, 2;

CREATE OR REPLACE DYNAMIC TABLE RETAIL_DWH.GOLD.CUSTOMER_SEGMENTS
    TARGET_LAG = '10 minutes'
    WAREHOUSE = TRANSFORM_WH
AS
SELECT
    o.CUSTOMER_ID,
    COUNT(*) AS ORDER_COUNT,
    SUM(o.AMOUNT) AS LIFETIME_VALUE,
    CASE
        WHEN SUM(o.AMOUNT) >= 1000 THEN 'high_value'
        WHEN SUM(o.AMOUNT) >= 200  THEN 'mid_value'
        ELSE 'low_value'
    END AS SEGMENT
FROM RETAIL_DWH.SILVER.CLEAN_ORDERS o
GROUP BY o.CUSTOMER_ID;
