-- Change data capture via Streams + Tasks: a procedural alternative to the
-- declarative Dynamic Tables in 04_gold_metrics.sql, demonstrated separately
-- for an audit-style trail of inserted order records.

CREATE OR REPLACE STREAM RETAIL_DWH.BRONZE.ORDER_CHANGES
    ON TABLE RETAIL_DWH.BRONZE.RAW_ORDERS;

CREATE TABLE IF NOT EXISTS RETAIL_DWH.SILVER.ORDER_AUDIT (
    ORDER_ID      NUMBER,
    STATUS        VARCHAR,
    AMOUNT        NUMBER(12,2),
    PROCESSED_AT  TIMESTAMP_NTZ
);

CREATE OR REPLACE TASK RETAIL_DWH.BRONZE.PROCESS_ORDER_CHANGES
    WAREHOUSE = TRANSFORM_WH
    SCHEDULE = '1 MINUTE'
    WHEN SYSTEM$STREAM_HAS_DATA('RETAIL_DWH.BRONZE.ORDER_CHANGES')
AS
INSERT INTO RETAIL_DWH.SILVER.ORDER_AUDIT
    (ORDER_ID, STATUS, AMOUNT, PROCESSED_AT)
SELECT
    ORDER_ID, STATUS, AMOUNT, CURRENT_TIMESTAMP()
FROM RETAIL_DWH.BRONZE.ORDER_CHANGES
WHERE METADATA$ACTION = 'INSERT';

-- Task is created suspended by default; resume explicitly once validated.
ALTER TASK RETAIL_DWH.BRONZE.PROCESS_ORDER_CHANGES RESUME;

-- Run-log entry for this task's executions, consumed by monitoring/freshness_checks.sql.
CREATE TABLE IF NOT EXISTS RETAIL_DWH.SILVER.PIPELINE_RUN_LOG (
    PIPELINE_NAME   VARCHAR,
    RUN_STARTED_AT  TIMESTAMP_NTZ,
    RUN_ENDED_AT    TIMESTAMP_NTZ,
    ROWS_PROCESSED  NUMBER,
    ROWS_REJECTED   NUMBER,
    STATUS          VARCHAR
);
